"""Estimate independent-library variability without using any final seed."""
import datetime
import math
import os
import shutil
import subprocess
import sys
import time

import numpy as np
import pandas as pd
from scipy.stats import norm, nct, t
from common import HERE, REFERENCE, EARLIER, LIBRARY, TOOLS, ENVIRONMENT, sha, save, load, preserve_reference, verify_outputs
from metrics import score


def main():
    preserve_reference()
    plan = load(HERE / 'pilot_protocol.json')
    files = [HERE / n for n in ['common.py', 'pilot.py', 'pilot_protocol.json', 'worker.py', 'metrics.py']]
    files += [TOOLS / n for n in ['Shepherd/shepherd_t0.py', 'starcode/starcode', 'bartender-1.1/bartender_single']]
    inputs = []
    for seed in plan['seeds']:
        for condition in plan['designs']:
            data = REFERENCE / 'generated/datasets' / condition if seed == 2026091201 else EARLIER / 'generated/pilot' / str(seed) / (condition.split('_')[0] + '_x1') / 'data'
            verify_outputs(data, load(data / 'dataset.json')['sha256'])
            inputs.append((seed, condition, data))
            files += [data / n for n in ['input.csv', 'input.tsv', 'truth.csv', 'labels.csv']]
    fingerprints = {str(p): sha(p) for p in files}
    freeze = HERE / 'pilot_freeze.json'
    if freeze.exists():
        assert load(freeze)['sha256'] == fingerprints
    else:
        save(freeze, dict(frozen_at=datetime.datetime.now(datetime.timezone.utc).isoformat(), sha256=fingerprints))
    results, new_runs = [], 0
    for seed, condition, data in inputs:
        input_df, truth, labels = (pd.read_csv(data / n) for n in ['input.csv', 'truth.csv', 'labels.csv'])
        for method in plan['methods']:
            if seed == 2026091201:
                directory = REFERENCE / 'generated/baseline' / condition / method
                previous = load(directory / 'result.json')
                verify_outputs(directory, previous['output_sha256'])
                result = dict(seed=seed, condition=condition, method=method, source='original frozen development cache', **{k: previous[k] for k in ['f1_percent', 'fn', 'fp']})
            elif method in ['hamming', 'lv']:
                if method == 'hamming':
                    # Only LV comparisons determine sample size. No reason to run
                    # a missing Hamming pilot purely to fill an ancillary row.
                    continue
                directory = data.parent / 'poisson'
                previous = load(directory / 'result.json')
                verify_outputs(directory, previous['sha256'])
                result = dict(seed=seed, condition=condition, method=method, source='validated unchanged-v14 Poisson path in previous experiment', **{k: previous[k] for k in ['f1_percent', 'fn', 'fp']})
            else:
                directory = HERE / 'generated/pilot' / str(seed) / condition / method
                if (directory / 'result.json').exists():
                    result = load(directory / 'result.json')
                    verify_outputs(directory, result['sha256'])
                    results.append(result)
                    continue
                directory.mkdir(parents=True, exist_ok=False)
                shutil.copyfile(data / 'input.tsv', directory / 'input.tsv')
                cmd = [sys.executable, str(HERE / 'worker.py'), method, str(data), str(directory), str(TOOLS), str(LIBRARY), str(load(data / 'dataset.json')['nominal_length'])]
                print('PILOT', seed, condition, method, flush=True)
                start = time.perf_counter()
                with (directory / 'worker.log').open('w') as stream:
                    subprocess.run(cmd, env={**os.environ, **ENVIRONMENT}, stdout=stream, stderr=subprocess.STDOUT, check=True, timeout=960)
                elapsed = time.perf_counter() - start
                metrics = score(pd.read_csv(directory / 'centroids.csv'), pd.read_csv(directory / 'members.csv'), input_df, truth, labels)
                result = dict(seed=seed, condition=condition, method=method, source='new development pilot', **metrics,
                    workflow_seconds=elapsed, command=cmd,
                    sha256={n: sha(directory / n) for n in ['centroids.csv', 'members.csv', 'worker.json']})
                save(directory / 'result.json', result)
                # Disposable expansion generated by this invocation, never source data.
                if (directory / 'expanded.csv').exists():
                    (directory / 'expanded.csv').unlink()
                new_runs += 1
            results.append(result)
            save(HERE / 'pilot_results.json', results)
    save(HERE / 'pilot_results.json', results)
    df = pd.DataFrame(results)
    df.to_csv(HERE / 'pilot_results.csv', index=False)
    contrasts = []
    for condition in plan['designs']:
        table = df[df.condition == condition].pivot(index='seed', columns='method', values='f1_percent')
        for competitor in ['shepherd', 'starcode_sphere', 'starcode_mp', 'bartender']:
            difference = table.lv - table[competitor]
            assert len(difference) == 4 and difference.notna().all()
            contrasts.append(dict(condition=condition, competitor=competitor,
                n=4, mean_difference=float(difference.mean()), sd=float(difference.std(ddof=1)),
                differences=difference.to_dict()))
    rule = plan['final_sample_size_rule']
    alpha = rule['alpha_familywise'] / rule['primary_contrasts']
    delta = rule['target_effect_F1_percentage_points']
    for row in contrasts:
        sd = row['sd']
        row['normal_approx_required_n'] = math.ceil(((norm.ppf(1-alpha) + norm.ppf(rule['power_target'])) * sd / delta) ** 2)
    required = max(row['normal_approx_required_n'] for row in contrasts)
    selected = min(rule['maximum_per_design'], max(rule['minimum_per_design'], math.ceil(required / 5) * 5))
    for row in contrasts:
        noncentrality = delta * np.sqrt(selected) / row['sd'] if row['sd'] else float('inf')
        row['approx_power_at_selected_n'] = float(nct.sf(t.ppf(1-alpha, selected-1), selected-1, noncentrality)) if row['sd'] else 1.0
        row['approx_90pct_detectable_difference'] = float((norm.ppf(1-alpha) + norm.ppf(rule['power_target'])) * row['sd'] / np.sqrt(selected))
    save(HERE / 'sample_size.json', dict(selected_n_per_design=selected, normal_approx_required_n=required,
        target_difference_percentage_points=delta, familywise_alpha=rule['alpha_familywise'], power_target=rule['power_target'],
        budget_cap_binding=required > rule['maximum_per_design'], contrasts=contrasts,
        caveat='Four pilot libraries per design give uncertain variance estimates. Approximate power is planning information, not guaranteed superiority. Final n will not increase after examining outcomes.',
        final_seeds_evaluated=False))
    assert {str(p): sha(p) for p in files} == fingerprints
    preserve_reference()
    print('SAMPLE SIZE', selected, 'per design; uncapped approximation', required, flush=True)


if __name__ == '__main__':
    main()
